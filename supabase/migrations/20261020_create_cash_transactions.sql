create table if not exists public.cash_transactions (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    transaction_type text not null
        check (transaction_type in ('deposit', 'withdrawal')),
    amount_cents bigint not null check (amount_cents > 0),
    timestamp timestamptz not null default now(),
    note text not null default ''
);

create index if not exists cash_transactions_user_timestamp_idx
    on public.cash_transactions (user_id, timestamp desc, id desc);

alter table public.cash_transactions enable row level security;

drop policy if exists "Users can read their own cash transactions"
    on public.cash_transactions;
create policy "Users can read their own cash transactions"
    on public.cash_transactions
    for select
    to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert their own cash transactions"
    on public.cash_transactions;
create policy "Users can insert their own cash transactions"
    on public.cash_transactions
    for insert
    to authenticated
    with check ((select auth.uid()) = user_id);

revoke all on public.cash_transactions from public, anon, authenticated;
grant select, insert on public.cash_transactions to authenticated;

create or replace function public.record_cash_transaction(
    p_transaction_type text,
    p_amount_cents bigint,
    p_note text default ''
)
returns void
language plpgsql
security invoker
set search_path = ''
as $function$
declare
    v_user_id uuid := auth.uid();
    v_balance bigint;
begin
    if v_user_id is null then
        raise exception 'Authentication is required to record cash transactions.';
    end if;

    if p_transaction_type is null or p_transaction_type not in ('deposit', 'withdrawal') then
        raise exception 'Transaction must be a deposit or withdrawal.';
    end if;

    if p_amount_cents is null or p_amount_cents <= 0 then
        raise exception 'Amount must be greater than zero.';
    end if;

    perform pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(v_user_id::text, 0)
    );

    select coalesce(
        sum(
            case transaction_type
                when 'deposit' then amount_cents
                else -amount_cents
            end
        ),
        0
    )::bigint
    into v_balance
    from public.cash_transactions
    where user_id = v_user_id;

    if p_transaction_type = 'withdrawal' and p_amount_cents > v_balance then
        raise exception 'Withdrawal exceeds the available cash balance.';
    end if;

    insert into public.cash_transactions (user_id, transaction_type, amount_cents, note)
    values (v_user_id, p_transaction_type, p_amount_cents, coalesce(p_note, ''));
end;
$function$;

revoke all on function public.record_cash_transaction(text, bigint, text)
    from public, anon, authenticated;
grant execute on function public.record_cash_transaction(text, bigint, text)
    to authenticated;
